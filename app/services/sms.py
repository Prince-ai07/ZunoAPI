# app/services/sms.py
#
# Handles all SMS sending for the Zuno platform.
# Uses Africa's Talking — a Kenyan SMS API that works
# Excellently works with Safaricom, Airtel, and Telkom numbers.
#
# Every important event on Zuno triggers an SMS:
# - OTP verification codes
# - Deal funded confirmation
# - Item shipped notification
# - Delivery confirmation
# - Dispute alerts
# - Fund release confirmation
#
# SMS is critical in Kenya because:
# 1. Not everyone has a smartphone with internet
# 2. SMS works even on basic phones
# 3. Kenyans trust SMS confirmations for financial transactions

import africastalking
import os

# Initialize Africa's Talking with credentials from .env
# In sandbox mode, no real SMS is sent — it shows in the AT dashboard
africastalking.initialize(
    username=os.getenv('AT_USERNAME', 'sandbox'),
    api_key=os.getenv('AT_API_KEY', '')
)

# Get the SMS service object
sms = africastalking.SMS


def send_sms(phone_number, message):
    """
    Sends an SMS to a single phone number.

    Automatically formats the number to international format
    because Africa's Talking requires +254XXXXXXXXX format.

    Args:
        phone_number : Kenyan number e.g. "0712345678"
        message      : The text to send

    Returns:
        True  if SMS was sent successfully
        False if SMS failed (we log the error but don't crash)

    WHY WE CATCH EXCEPTIONS HERE:
    If SMS sending fails, we do NOT want the entire transaction
    to fail because of it. The transaction is more important
    than the notification. We log the failure and move on.
    """
    try:
        # Convert to international format if needed
        if phone_number.startswith('0'):
            phone_number = '+254' + phone_number[1:]
        elif phone_number.startswith('254'):
            phone_number = '+' + phone_number

        response = sms.send(
            message=message,
            recipients=[phone_number],
            sender_id=os.getenv('AT_SENDER_ID', 'ZUNO')
        )

        print(f"[SMS] Sent to {phone_number}: {response}")
        return True

    except Exception as e:
        # Log the error but don't crash the application
        print(f"[SMS ERROR] Failed to send to {phone_number}: {str(e)}")
        return False


def send_otp(phone_number, otp_code):
    """
    Sends a formatted OTP verification message.

    We keep this message very clear and include a warning
    never to share the code — educates users against
    social engineering attacks from day one.

    Args:
        phone_number : number to send OTP to
        otp_code     : the 6-digit code generated by auth route
    """
    message = (
        f"Your Zuno verification code is: {otp_code}. "
        f"Valid for 10 minutes. "
        f"Never share this code with anyone. "
        f"Zuno will never ask for this code."
    )
    return send_sms(phone_number, message)


def send_deal_funded_notification(seller_phone, item_name, amount, transaction_id):
    """
    Notifies seller that a buyer has funded their escrow deal.
    This is the seller's signal to ship the item.
    """
    message = (
        f"Zuno: FUNDS SECURED! "
        f"Ksh {amount:,.0f} is held in escrow for '{item_name}'. "
        f"Deal ID: {transaction_id}. "
        f"Please ship the item and mark it as shipped on Zuno."
    )
    return send_sms(seller_phone, message)


def send_item_shipped_notification(buyer_phone, item_name, tracking, transaction_id):
    """
    Notifies buyer that their item has been shipped.
    """
    tracking_info = f"Tracking: {tracking}." if tracking else "No tracking number provided."
    message = (
        f"Zuno: Your order '{item_name}' has been shipped! "
        f"{tracking_info} "
        f"Once received, confirm delivery on Zuno to release payment. "
        f"Deal ID: {transaction_id}"
    )
    return send_sms(buyer_phone, message)


def send_delivery_confirmed_notification(seller_phone, item_name, amount):
    """
    Notifies seller that buyer confirmed delivery and funds are releasing.
    """
    message = (
        f"Zuno: Great news! Buyer confirmed delivery of '{item_name}'. "
        f"Ksh {amount:,.0f} is being released to your M-Pesa. "
        f"Thank you for using Zuno!"
    )
    return send_sms(seller_phone, message)


def send_dispute_notification(phone_number, transaction_id, raised_by):
    """
    Notifies both parties when a dispute is raised.
    """
    message = (
        f"Zuno: A dispute has been raised on deal {transaction_id}. "
        f"Funds are frozen until resolved. "
        f"Log in to Zuno to respond and submit evidence. "
        f"You have 48 hours to respond."
    )
    return send_sms(phone_number, message)


def send_funds_released_notification(seller_phone, amount, mpesa_ref):
    """
    Notifies seller when their M-Pesa payout is sent.
    """
    message = (
        f"Zuno: Ksh {amount:,.0f} has been sent to your M-Pesa. "
        f"M-Pesa Reference: {mpesa_ref}. "
        f"Thank you for selling on Zuno!"
    )
    return send_sms(seller_phone, message)


def send_refund_notification(buyer_phone, amount, item_name):
    """
    Notifies buyer when their refund is being processed.
    """
    message = (
        f"Zuno: Your refund of Ksh {amount:,.0f} for '{item_name}' "
        f"is being processed to your M-Pesa. "
        f"This may take up to 24 hours."
    )
    return send_sms(buyer_phone, message)